#variavel boolean serve ao questionar algo em um programa, retornando True (sim) ou False (não)
#só existem essas duas possibilidades

#existem vários operadores para questionar, sendo eles == (igual), != (diferente), < (menor), <= (menor igual), > (maior), >= (maior igual)
print(10 == 0) #está comparando igualdade, vai dar False, pois são diferentes
print(10 == 10) #vai dar True, pois são iguais
print(type(10==10)) #mostrando que o tipo de dado é bool
print(type(True)) #Vai mostrar que é um tipo bool, mesmo que seja um texto, pois o True fora de aspas é lido como bool
print(type(False)) #Mesma coisa com o False

